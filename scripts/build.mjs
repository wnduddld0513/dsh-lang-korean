// Build one chunk per translation pack, lib/client.<pack>-ko.js, from i18n/<pack>/ko.json checked
// against i18n/<pack>/source.json. A translation whose {placeholders} differ from its source text
// (Japanese for DeepSeek Harness, English for plugins), or that carries U+200B / U+FEFF, fails the
// build; an untranslated entry only warns, because the page then shows the English text.
//
//   node scripts/build.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (path) => JSON.parse(readFileSync(join(ROOT, path), 'utf8'))
const placeholders = (text) => [...new Set(text.match(/\{\w+\}/g) ?? [])].sort().join(' ')
const label = (text) => JSON.stringify(text).slice(0, 60)
const list = (items) => `${items.slice(0, 20).join('\n  ')}${items.length > 20 ? '\n  …' : ''}`

let failed = false
for (const pack of readdirSync(join(ROOT, 'i18n')).sort()) {
  if (!existsSync(join(ROOT, `i18n/${pack}/ko.json`))) {
    console.warn(`skip ${pack}: i18n/${pack}/ko.json does not exist yet`)
    continue
  }
  const source = read(`i18n/${pack}/source.json`)
  const ko = read(`i18n/${pack}/ko.json`)
  const errors = []
  const missing = []
  const take = (where, original, translated) => {
    if (typeof translated !== 'string') {
      missing.push(where)
      return false
    }
    if (/[\u200B\uFEFF]/.test(translated)) errors.push(`${where}: contains U+200B or U+FEFF`)
    if (placeholders(original) !== placeholders(translated)) errors.push(`${where}: placeholders ${placeholders(original) || '(none)'} ≠ ${placeholders(translated) || '(none)'}`)
    return true
  }

  const dictionaries = {}
  for (const [ns, keys] of Object.entries(source.ui ?? {})) {
    for (const [key, text] of Object.entries(keys)) {
      const translated = ko.ui?.[ns]?.[key]
      if (take(`ui ${ns} ${key}`, text.ja ?? text.en, translated)) (dictionaries[ns] ??= {})[key] = translated
    }
  }
  // Display text without keys: by Japanese original (DeepSeek Harness package meta) or by English.
  const byText = (field) => {
    const out = {}
    for (const original of Object.keys(source[field] ?? {})) {
      const translated = ko[field]?.[original]
      if (take(`${field} ${label(original)}`, original, translated)) out[original] = translated
    }
    return out
  }
  const packageText = byText('packageText')
  const englishText = byText('englishText')
  const stale = [
    ...Object.entries(ko.ui ?? {}).flatMap(([ns, keys]) => Object.keys(keys).filter((key) => source.ui?.[ns]?.[key] === undefined).map((key) => `ui ${ns} ${key}`)),
    ...['packageText', 'englishText'].flatMap((field) => Object.keys(ko[field] ?? {}).filter((text) => source[field]?.[text] === undefined).map((text) => `${field} ${label(text)}`)),
  ]

  const origin = source.dshVersion ? `DeepSeek Harness ${source.dshVersion}` : `${source.package}@${source.version}`
  if (errors.length) {
    failed = true
    for (const error of errors) console.error(`error: ${pack}: ${error}`)
    continue
  }
  const exports = { dictionaries, packageText, englishText }
  const chunk = `client.${pack}-ko.js`
  const body = `// Generated by scripts/build.mjs from i18n/${pack}/ko.json for ${origin}. Do not edit.
window.__ModuleLoader__.load({
  id: 'dsh-lang-korean',
  chunk: '${chunk}',
  factory: () => ({
${Object.entries(exports).filter(([, value]) => Object.keys(value).length).map(([name, value]) => `    ${name}: ${JSON.stringify(value)},`).join('\n')}
  }),
})
`
  writeFileSync(join(ROOT, 'lib', chunk), body)
  const keys = Object.values(dictionaries).reduce((sum, dict) => sum + Object.keys(dict).length, 0)
  console.log(`lib/${chunk}: ${Object.keys(dictionaries).length} namespaces, ${keys} keys, ${Object.keys(packageText).length + Object.keys(englishText).length} display texts (${origin})`)
  if (missing.length) console.warn(`warning: ${pack}: ${missing.length} untranslated (shown in English):\n  ${list(missing)}`)
  if (stale.length) console.warn(`warning: ${pack}: ${stale.length} translations no longer in the source:\n  ${list(stale)}`)
}
if (failed) process.exit(1)
